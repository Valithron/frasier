export const EPISODES: Episode[] = SEASON_TITLES.flatMap((titles, seasonIndex) =>
  titles.map((title, episodeIndex) => ({
    season: seasonIndex + 1,
    episode: episodeIndex + 1,
    key: `${seasonIndex + 1}-${episodeIndex + 1}`,
    title,
  })),
);

export const episodeFor = (season: number, episode: number) =>
  EPISODES.find((item) => item.season === season && item.episode === episode);

export const episodesForSeason = (season: number) =>
  EPISODES.filter((item) => item.season === season);
